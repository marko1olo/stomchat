def normalize_dental_compounds(text: str) -> str:
    """Нормализует составные стоматологические термины (e.max -> emax, cad/cam -> cadcam) и букву ё."""
    if not text:
        return ""
    t = text.replace('ё', 'е').replace('Ё', 'Е')
    for pattern, repl in COMPOUND_NORM:
        t = pattern.sub(repl, t)
    return t

