CODE_RE = re.compile(r"^\d{1,2}(?:\.\d{1,2}){1,3}$")


def normalize_code(code):
    """Код без окружающих пробелов. В базе есть значения вида ' 2.1.1 '."""
    return str(code if code is not None else "").strip()


def parse_codes(value):
    """Разбирает список кодов через запятую в кортеж без повторов.

    99.1 % записей вики (12 667 из 12 784) хранят в `category_code` СПИСОК: разных
    значений 6 711 при 110 реальных кодах. Точное сравнение со значением не
    совпадает почти никогда, поэтому любой отбор обязан идти по токенам. Иначе
    факт с двумя тегами виден только в одном разделе, а второй раздел для врача
    пуст.
    """
    codes = []
    for chunk in str(value if value is not None else "").split(","):
        code = chunk.strip()
        if code and code not in codes:
            codes.append(code)
    return tuple(codes)


def has_name(code):
    """Есть ли у кода достоверное имя (из дерева), а не заглушка."""
    return normalize_code(code) in DISPLAY_NAMES


def display_name(code):
    """Человеческое имя кода либо честная пометка «БЕЗ ИМЕНИ».

    Пометка обязана быть видимой: под безымянным кодом в базе лежат живые факты
    (49 кодов, 302 пометки), и если показать их без имени раздела, врач решит, что
    раздел пустой, а не что рубрика потеряна.
    """
    code = normalize_code(code)
    if code in DISPLAY_NAMES:
        return DISPLAY_NAMES[code]
    return UNNAMED_PREFIX + code


def describe(code):
    """Имя кода с контекстом раздела, когда сам код имени не имеет.

    Раздел выводится из самого кода, а не придумывается: `6.1.2` -> «ОБЩЕЕ». Врач
    хотя бы понимает, в какой части дерева находится факт.
    """
    code = normalize_code(code)
    if code in DISPLAY_NAMES:
        return DISPLAY_NAMES[code]
    section = SECTION_NAMES.get(code.split(".")[0])
    if section:
        return f"{UNNAMED_PREFIX}{code} (раздел {code.split('.')[0]} {section})"
    return UNNAMED_PREFIX + code


def is_exportable(code):
    """Попадёт ли факт с этим кодом хотя бы в один файл выгрузки."""
    return normalize_code(code) in EXPORT_SLUGS


def export_slug(code):
    """Имя файла выгрузки без расширения либо None, если рубрики нет."""
    return EXPORT_SLUGS.get(normalize_code(code))


def code_is_valid(code):
    """Форма кода пригодна для подстановки в LIKE."""
    return bool(CODE_RE.match(normalize_code(code)))


