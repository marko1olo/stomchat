def evaluate_vdo_phonetics(
    s_gap_mm: float = 1.5,
    fv_lip_contact: str = "dry_wet_line",
    m_lips_strain: bool = False,
    clattering: bool = False
) -> Dict[str, Any]:
    """Комплексная оценка фонетических проб («М», «С»/«З», «В»/«Ф») при определении VDO."""
    status_pass = True
    clinical_flags = []
    recommendations = []
    if clattering or s_gap_mm < CLOSEST_SPEAKING_SPACE_MIN_MM:
        status_pass = False
        clinical_flags.append("Звуки «С», «З»: стук зубов (clattering) / зазор <1.0 мм -> ВНОЛ ЗАВЫШЕНА!")
        recommendations.append("Немедленно сошлифовать окклюзионную поверхность или снизить прикус на 1–2 мм.")
    elif s_gap_mm > 2.0:
        status_pass = False
        clinical_flags.append(f"Звуки «С», «З»: разговорный зазор {s_gap_mm:.1f} мм > нормы (1–2 мм) -> занижение VDO или избыточный оверджет.")
        recommendations.append("Проверить сагиттальное резцовое перекрытие и высоту окклюзии.")

    if fv_lip_contact == "dry_vermilion":
        status_pass = False
        clinical_flags.append("Звуки «В», «Ф»: контакт на сухой красной кайме -> резцы слишком длинные или протрузия.")
        recommendations.append("Укоротить режущие края на 1–1.5 мм или наклонить резцы палатально.")
    elif fv_lip_contact == "wet_mucosa":
        status_pass = False
        clinical_flags.append("Звуки «В», «Ф»: контакт на влажной слизистой рта -> резцы слишком короткие или ретрузия.")
        recommendations.append("Удлинить режущие края или выдвинуть резцы вестибулярно для поддержки губы.")

    if m_lips_strain:
        status_pass = False
        clinical_flags.append("Звук «М»: напряжение круговой мышцы рта при смыкании губ -> завышение VDO.")
        recommendations.append("Повторить замер VDR снаружи без валиков, губы должны смыкаться мягко без усилия.")

    if status_pass:
        return {
            "status": "PASS",
            "summary": "Все фонетические пробы («М», «С»/«З», «В»/«Ф») строго в норме. Межальвеолярная высота и положение резцов идеальны.",
            "recommendation": "Окклюзия и фонетика верифицированы для постоянного протезирования."
        }
    return {"status": "CORRECTION_NEEDED", "summary": " | ".join(clinical_flags), "recommendation": " | ".join(recommendations)}

