def calculate_vdo_from_vdr(vdr_mm: float, freeway_space_mm: float = FREEWAY_SPACE_DEFAULT_MM) -> VDOEvaluationResult:
    """
    Расчет высоты нижней трети лица в окклюзии (VDO) по высоте физиологического покоя (VDR).
    VDO = VDR - Freeway space.
    """
    if vdr_mm <= 0:
        return VDOEvaluationResult(
            vdr_mm=0.0,
            freeway_space_mm=freeway_space_mm,
            vdo_mm=0.0,
            is_valid_range=False,
            diagnostic_comment="Ошибка: некорректное значение VDR (должно быть положительным числом)."
        )

    is_valid = FREEWAY_SPACE_MIN_MM <= freeway_space_mm <= FREEWAY_SPACE_MAX_MM
    vdo = vdr_mm - freeway_space_mm

    if freeway_space_mm < FREEWAY_SPACE_MIN_MM:
        comment = (
            f"ВНИМАНИЕ: Зазор {freeway_space_mm:.1f} мм меньше клинической нормы (2–4 мм). "
            f"Высота прикуса (VDO = {vdo:.1f} мм) завышена! Риск гипертонуса жевательных мышц."
        )
    elif freeway_space_mm > FREEWAY_SPACE_MAX_MM:
        comment = (
            f"ВНИМАНИЕ: Зазор {freeway_space_mm:.1f} мм превышает клиническую норму (2–4 мм). "
            f"Высота прикуса (VDO = {vdo:.1f} мм) занижена! Риск дисфункции ВНЧС и укорочения лица."
        )
    else:
        comment = (
            f"НОРМА: Межокклюзионный промежуток {freeway_space_mm:.1f} мм строго в физиологическом окне (2–4 мм). "
            f"Целевая высота прикуса VDO = {vdo:.1f} мм."
        )

    return VDOEvaluationResult(
        vdr_mm=round(vdr_mm, 1),
        freeway_space_mm=round(freeway_space_mm, 1),
        vdo_mm=round(vdo, 1),
        is_valid_range=is_valid,
        diagnostic_comment=comment
    )


def diagnose_speaking_space_issue(
    observed_s_gap_mm: float,
    has_clattering: bool = False,
    has_lisping: bool = False
) -> Dict[str, str]:
    """
    Клиническая дифференциальная диагностика ошибок высоты прикуса по звуку «С».
    """
    issues = []
    actions = []

    if has_clattering or observed_s_gap_mm < CLOSEST_SPEAKING_SPACE_MIN_MM:
        issues.append("Соударение / стук зубов (Clattering): ВНОЛ ЗАВЫШЕНА (межальвеолярная высота чрезмерна).")
        actions.append(f"Уменьшить высоту окклюзионных валиков/зубов на {CLOSEST_SPEAKING_SPACE_MIN_MM - observed_s_gap_mm + 0.5:.1f}–1.0 мм.")

    if has_lisping:
        issues.append("Шепелявость (Lisping): ВНОЛ занижена, избыточный сагиттальный зазор или переутолщение базиса на небе.")
        actions.append("Проверить толщину небного свода протеза (истончить до 1.5 мм в зоне складок), уменьшить оверджет.")

    if not issues:
        return {
            "status": "PASS",
            "summary": f"Разговорное пространство в норме ({observed_s_gap_mm:.1f} мм). Соударения и шепелявости нет.",
            "recommendation": "Окклюзионная плоскость и высота прикуса в переднем отделе верифицированы."
        }

    return {
        "status": "CORRECTION_NEEDED",
        "summary": " | ".join(issues),
        "recommendation": " | ".join(actions)
    }


def check_pound_line_compliance(lingual_overhang_mm: float) -> Tuple[bool, str]:
    """
    Проверка постановки боковых зубов нижней челюсти по линии Паунда.
    lingual_overhang_mm: выход язычных бугров медиальнее язычной линии Паунда (в мм).
    """
    if lingual_overhang_mm <= 0.0:
        return True, "Постановка зубов корректна: язычные бугры не пересекают линию Паунда. Пространство для языка свободно."
    else:
        return False, (
            f"ОШИБКА ПОСТАНОВКИ: Язычные бугры выходят внутрь на {lingual_overhang_mm:.1f} мм за линию Паунда! "
            "Критический риск сбрасывания нижнего протеза корнем языка и прикусывания боковых краев языка. "
            "Необходимо сузить постановку или сместить моляры вестибулярно в пределы гребня."
        )


