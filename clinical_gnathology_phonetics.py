def calculate_vdo_from_vdr(vdr_mm: float, freeway_space_mm: float = FREEWAY_SPACE_DEFAULT_MM) -> VDOEvaluationResult:
    """Расчет высоты нижней трети лица в окклюзии (VDO = VDR - Freeway space)."""
    if vdr_mm <= 0:
        return VDOEvaluationResult(0.0, freeway_space_mm, 0.0, False, "Ошибка: некорректное значение VDR.")
    is_valid = FREEWAY_SPACE_MIN_MM <= freeway_space_mm <= FREEWAY_SPACE_MAX_MM
    vdo = vdr_mm - freeway_space_mm
    if freeway_space_mm < FREEWAY_SPACE_MIN_MM:
        comment = f"ВНИМАНИЕ: Зазор {freeway_space_mm:.1f} мм меньше нормы (2–4 мм). VDO={vdo:.1f} мм завышена! Спазм жевательных мышц."
    elif freeway_space_mm > FREEWAY_SPACE_MAX_MM:
        comment = f"ВНИМАНИЕ: Зазор {freeway_space_mm:.1f} мм превышает норму (2–4 мм). VDO={vdo:.1f} мм занижена! Риск дисфункции ВНЧС."
    else:
        comment = f"НОРМА: Межокклюзионный промежуток {freeway_space_mm:.1f} мм в норме (2–4 мм). Целевая VDO = {vdo:.1f} мм."
    return VDOEvaluationResult(round(vdr_mm, 1), round(freeway_space_mm, 1), round(vdo, 1), is_valid, comment)

def diagnose_speaking_space_issue(
    observed_s_gap_mm: float,
    has_clattering: bool = False,
    has_lisping: bool = False
) -> Dict[str, str]:
    """Клиническая дифференциальная диагностика ошибок высоты прикуса по звукам «С», «З»."""
    issues = []
    actions = []
    if has_clattering or observed_s_gap_mm < CLOSEST_SPEAKING_SPACE_MIN_MM:
        issues.append("Соударение / стук зубов (Clattering): ВНОЛ ЗАВЫШЕНА (межальвеолярная высота чрезмерна).")
        actions.append(f"Уменьшить высоту окклюзионных валиков/зубов на {CLOSEST_SPEAKING_SPACE_MIN_MM - observed_s_gap_mm + 0.5:.1f}–1.0 мм.")
    if has_lisping or observed_s_gap_mm > 2.5:
        issues.append("Шепелявость / свист (Lisping): ВНОЛ занижена, избыточный сагиттальный зазор или переутолщение базиса на небе.")
        actions.append("Проверить толщину небного свода протеза (истончить до 1.5–2.0 мм в зоне складок), уменьшить оверджет.")
    if not issues:
        return {
            "status": "PASS",
            "summary": f"Разговорное пространство в норме ({observed_s_gap_mm:.1f} мм). Соударения и шепелявости нет.",
            "recommendation": "Окклюзионная плоскость и высота прикуса в переднем отделе верифицированы."
        }
    return {"status": "CORRECTION_NEEDED", "summary": " | ".join(issues), "recommendation": " | ".join(actions)}

