@dataclass(frozen=True)
class PhoneticTest:
    """Клиническая спецификация фонетической пробы."""
    key: str; sound: str; author: str; target_landmark: str
    normal_interval_mm: str; protocol_steps: List[str]
    error_interpretations: Dict[str, str]; biomechanical_rationale: str

@dataclass
class VDOEvaluationResult:
    """Результат расчета вертикального размера окклюзии."""
    vdr_mm: float; freeway_space_mm: float; vdo_mm: float
    is_valid_range: bool; diagnostic_comment: str

@dataclass(frozen=True)
class OcclusionGuidanceSpec:
    """Спецификация типа функционального ведения зубных рядов."""
    key: str; title: str; indications: List[str]; contraindications: List[str]
    implant_risks: str; clinical_protocol: List[str]; biomechanical_rationale: str

@dataclass(frozen=True)
class InterferenceSpec:
    """Клиническая спецификация окклюзионной интерференции / суперконтакта."""
    key: str; title: str; location: str; clinical_dangers: str
    equilibration_rule: str; action_steps: List[str]

@dataclass(frozen=True)
class EHRTemplateSpec:
    """Экспресс-шаблон протокола для электронной медицинской карты (МИС/ЕМИАС)."""
    key: str; title: str; description: str; template_text: str

