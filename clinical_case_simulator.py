def get_clinical_case_by_id(case_id: str) -> Optional[Dict[str, Any]]:
    """Находит кейс из банка по его ID."""
    for c in CLINICAL_CASE_BANK:
        if c["case_id"] == case_id:
            return c
    return None


def get_random_clinical_case() -> Dict[str, Any]:
    """Возвращает случайный острый клинический кейс из банка."""
    return random.choice(CLINICAL_CASE_BANK)


