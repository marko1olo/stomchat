def normalize_tooth_fdi(tooth_raw: Union[int, str]) -> Dict[str, str]:
    """
    Нормализует обозначение зуба по формуле FDI (ISO 3950).
    Принимает форматы: 37, 3.7, "37", "3.7", "зуб 37", "зуб 3.7".
    Возвращает словарь с нормализованным номером, квадрантом, челюстью и названием.
    """
    s = str(tooth_raw).strip().lower()
    match = re.search(r"([1-4])\s*[.\-_/]?\s*([1-8])", s)
    if not match:
        # Проверяем временный прикус (51-85)
        match_ped = re.search(r"([5-8])\s*[.\-_/]?\s*([1-5])", s)
        if match_ped:
            q, t = match_ped.group(1), match_ped.group(2)
            fdi_dot = f"{q}.{t}"
            fdi_num = f"{q}{t}"
            return {
                "fdi_dot": fdi_dot,
                "fdi_num": fdi_num,
                "name": f"Временный зуб {fdi_dot}",
                "quadrant": f"Квадрант {q}",
                "jaw": "Верхняя челюсть" if q in ("5", "6") else "Нижняя челюсть",
                "side": "справа" if q in ("5", "8") else "слева",
            }
        # Дефолтный фоллбэк, если не спарсилось
        return {
            "fdi_dot": str(tooth_raw),
            "fdi_num": str(tooth_raw),
            "name": f"Зуб {tooth_raw}",
            "quadrant": "Не определен",
            "jaw": "Зубной ряд",
            "side": "",
        }

    q, t = match.group(1), match.group(2)
    fdi_dot = f"{q}.{t}"
    fdi_num = f"{q}{t}"

    jaw_names = {"1": "Верхняя челюсть, справа", "2": "Верхняя челюсть, слева",
                 "3": "Нижняя челюсть, слева", "4": "Нижняя челюсть, справа"}
    side_names = {"1": "справа", "2": "слева", "3": "слева", "4": "справа"}
    jaw_only = "Верхняя челюсть" if q in ("1", "2") else "Нижняя челюсть"

    tooth_names_map = {
        "1": "центральный резец",
        "2": "боковой резец",
        "3": "клык",
        "4": "первый премоляр",
        "5": "второй премоляр",
        "6": "первый моляр",
        "7": "второй моляр",
        "8": "третий моляр",
    }
    t_name = tooth_names_map.get(t, "зуб")
    full_name = f"{jaw_only}, {side_names.get(q, '')}, {t_name} (зуб {fdi_dot})"

    return {
        "fdi_dot": fdi_dot,
        "fdi_num": fdi_num,
        "name": full_name,
        "quadrant": f"Квадрант {q}",
        "jaw": jaw_only,
        "side": side_names.get(q, ""),
        "tooth_type": t_name,
    }


def normalize_diagnosis_icd(icd_raw: str) -> Dict[str, str]:
    """
    Нормализует код диагноза по МКБ-10.
    """
    clean = (icd_raw or "").strip().upper()
    # Ищем код типа K04.5, К04.5 (русская К), K04.03, K04.0, K02.1 и т.д.
    clean = clean.replace("К", "K")  # Cyrillic K to Latin K
    match = re.search(r"K\d{2}(?:\.\d{1,2})?", clean)
    code = match.group(0) if match else clean

    if code in ICD10_DENTAL_DIAGNOSES:
        return ICD10_DENTAL_DIAGNOSES[code]

    # Поиск по подстроке кода
    for c_key, data in ICD10_DENTAL_DIAGNOSES.items():
        if code.startswith(c_key) or c_key.startswith(code):
            return data

    # Если неизвестный код — формируем базовую запись
    return {
        "code": code or "K04.5",
        "name": icd_raw if icd_raw else "Заболевание периапикальных тканей/пульпы",
        "category": "Стоматологическая нозология",
        "clinical_manifestations": "Клинические признаки воспалительного процесса зубочелюстной системы.",
        "star_protocol": "Клинические рекомендации Стоматологической Ассоциации России (СтАР).",
        "recommended_tactics": "Комплексное эндодонтическое лечение по клиническим протоколам СтАР и МЗ РФ.",
    }


def get_procedure_justification(procedure_key: str, tooth_fdi: Union[int, str] = 37,
                                diagnosis_icd: str = "K04.5", findings: str = "") -> Dict[str, Any]:
    """
    Возвращает детальное медико-экономическое и клиническое обоснование для запрашиваемой процедуры.
    """
    key_low = procedure_key.lower().strip()

    # Определение категории процедуры
    category = "cbct"
    if any(w in key_low for w in ("микроскоп", "microscope", "оптика", "лейка", "цейс", "zeiss", "leica")):
        category = "microscope"
    elif any(w in key_low for w in ("ультразвук", "ultrasound", "start-x", "proultra", "насадк", "хелатор", "edta", "эдта")):
        category = "ultrasound_chelator"
    elif any(w in key_low for w in ("биокерамика", "bioceramic", "bioroot", "мта", "mta", "biodentine", "кальци", "calcium", "каласепт")):
        category = "bioceramics_calcium"
    elif any(w in key_low for w in ("кт", "клкт", "cbct", "томограф", "срез")):
        category = "cbct"

    info = INSTRUMENTAL_JUSTIFICATIONS.get(category, INSTRUMENTAL_JUSTIFICATIONS["cbct"])
    return {
        "procedure_category": category,
        "title": info["title"],
        "indications": info["clinical_indications"],
        "ebm_justification": info["ebm_justification"],
        "rejection_risk": info["insurance_rejection_risk"],
    }


