        f"<b>6. ЭКСПЕРТНОЕ ЗАКЛЮЧЕНИЕ О ЦЕЛЕСООБРАЗНОСТИ ЗУБОСОХРАНЯЮЩЕГО ЛЕЧЕНИЯ:</b>\n"
