def get_routine_clinical_protocol(query: str) -> Optional[str]:
    """
    Распознаёт 10 базовых рутинных клинических сценариев врача у кресла.
    Возвращает валидный доказательный EBM-протокол в строгом Telegram HTML.
    """
    if not query:
        return None
    lower = query.lower().strip()

    # 1. Альвеолит (сухая лунка 3-й день)
    if (
        re.search(r'\b(?:альвеолит\w*|сухая\s+лунк\w*|альвожил\w*|alvogyl)\b', lower)
        or (re.search(r'\b(?:лунк\w*|после\s+удалени\w*)\b', lower) and re.search(r'\b(?:болит|запах|пульсир\w*|распад\w*|3\s*день|3-й\s*день|3\s*дня)\b', lower))
    ):
        return PROTOCOL_ALVEOLITIS_DRY_SOCKET

    # 2. Фиксация циркония
    if (
        re.search(r'\b(?:циркон\w*|zirconia|zro2)\b', lower)
        and re.search(r'\b(?:фиксаци\w*|цементировк\w*|протокол|пескостру\w*|праймер|mdp|мдп|абрази\w*|apc)\b', lower)
    ):
        return PROTOCOL_ZIRCONIA_FIXATION

    # 3. Фиксация стеклокерамики (E.max)
    if (
        re.search(r'\b(?:e\.?max|дисиликат\w*|емакс)\b', lower)
        and re.search(r'\b(?:фиксаци\w*|цементировк\w*|протокол|травлен\w*|плавиков\w*|hf|силан\w*)\b', lower)
    ):
        return PROTOCOL_EMAX_FIXATION

    # 4. Атравматичное удаление и луночковое кровотечение
    if (
        re.search(r'\b(?:удалени\w*|экстракци\w*)\b', lower)
        and re.search(r'\b(?:моляр\w*|кровотеч\w*|губк\w*|швы|сгусток|атравматич\w*)\b', lower)
    ):
        return PROTOCOL_EXTRACTION_BLEEDING

    # 5. Адгезия при глубоком кариесе / Scotchbond Universal
    if (
        re.search(r'\b(?:scotchbond|скотчбонд)\b', lower)
        or (
            re.search(r'\b(?:глубок\w*\s+кариес\w*|кариес\s+дентин\w*)\b', lower)
            and re.search(r'\b(?:адгези\w*|бонд\w*|протокол|травлен\w*|втирани\w*)\b', lower)
        )
        or re.search(r'\b(?:избирательное\s+травление|селективное\s+травление\s+эмали)\b', lower)
    ):
        return PROTOCOL_DEEP_CARIES_ADHESION

    # 6. C-фактор и послойная полимеризация жевательной группы
    if (
        re.search(r'\b(?:c-фактор|с-фактор|c\s+фактор|с\s+фактор|cfactor)\b', lower)
        or (
            re.search(r'\b(?:жевательн\w*\s+групп\w*|моляр\w*|премоляр\w*)\b', lower)
            and re.search(r'\b(?:композит\w*|полимеризац\w*|стресс|послойн\w*|2\s*мм|bulk\s*fill)\b', lower)
        )
    ):
        return PROTOCOL_POSTERIOR_COMPOSITE_CFACTOR

    # 7. DME (Deep Margin Elevation)
    if (
        re.search(r'\b(?:dme|дме|deep\s+margin)\b', lower)
        or (
            re.search(r'\b(?:подняти\w*|элеваци\w*)\b', lower)
            and re.search(r'\b(?:поддеснев\w*|деснев\w*\s+кра\w*|кра\w*\s+полост\w*)\b', lower)
        )
    ):
        return PROTOCOL_DME_ELEVATION

    # 8. Обтурация (AH Plus vs Биокерамика, Tug-back, апикальный упор)
    if (
        re.search(r'\b(?:tug-back|таг-бэк|тагбэк|tug\s+back)\b', lower)
        or re.search(r'\b(?:апикальн\w*\s+упор\w*|припасовк\w*\s+гуттаперч\w*)\b', lower)
        or (
            re.search(r'\b(?:ah\s+plus|ах\s+плюс)\b', lower)
            and re.search(r'\b(?:биокерамик\w*|силер\w*|обтураци\w*)\b', lower)
        )
        or (
            re.search(r'\b(?:обтураци\w*|пломбировани\w*\s+канал\w*)\b', lower)
            and re.search(r'\b(?:силер\w*|биокерамик\w*|ah\s+plus)\b', lower)
        )
    ):
        return PROTOCOL_OBTURATING_SEALER_TUG_BACK

    # 9. Хемомеханическая обработка моляров (1.6, 3.6, 4.6)
    if (
        re.search(r'\b(?:хемомеханическ\w*|инструментаци\w*)\b', lower)
        and re.search(r'\b(?:моляр\w*|1\.6|3\.6|4\.6|каналов)\b', lower)
    ) or (
        re.search(r'\b(?:пульпит|периодонтит)\b', lower)
        and re.search(r'\b(?:1\.6|3\.6|4\.6)\b', lower)
        and re.search(r'\b(?:протокол|обработк\w*|каналы)\b', lower)
    ):
        return PROTOCOL_MOLAR_ENDO_PREP

    # 10. Ирригация NaOCl и EDTA
    if (
        lower in ("naocl", "edta", "гипохлорит", "ирригация", "протокол naocl", "протокол ирригации")
        or (
            re.search(r'\b(?:naocl|гипохлорит|эдта|edta)\b', lower)
            and re.search(r'\b(?:протокол|расчет|расчёт|объем|объём|активаци\w*|экспозици\w*|концентраци\w*)\b', lower)
        )
        or re.search(r'\b(?:протокол\s+ирригации|ирригационный\s+протокол|активация\s+гипохлорита)\b', lower)
    ):
        return PROTOCOL_ENDO_IRRIGATION

    return None
