"""
Разбор снимка: границы того, что бот вправе утверждать по картинке.

Описание снимка не остаётся внутри модели зрения — оно подставляется в
отвечающий промпт и становится основанием клинического комментария коллеге.
Значит выдуманная моделью находка превращается в клиническое утверждение.

Прежний промпт зрения прямо приглашал называть патологию («Опиши клиническую
картину: патология, этап лечения…») и не ограничивал домысливание ничем: ни
требования отделять увиденное от истолкованного, ни признания пределов снимка,
ни запрета на числа, которых на изображении не прочесть.

Отвечающий промпт, в свою очередь, подавал описание как факт.

Тест проверяет содержание промптов, а не поведение модели: доказать на
заглушках, что модель зрения станет осторожнее, нельзя — можно доказать, что
инструкция ей выдана и что оговорка доходит до отвечающего.

Запуск: python test_vision_safety.py
"""
import io
import re
import sys

for _stream in (sys.stdout, sys.stderr):
    try:
        _stream.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

PASS, FAIL = [], []


def check(name, cond, detail=""):
    (PASS if cond else FAIL).append(name)
    print(f"  [{'OK  ' if cond else 'FAIL'}] {name}" + (f" -- {detail}" if detail and not cond else ""))


VISION = io.open("vision.py", encoding="utf-8").read()
ASSISTANT = io.open("assistant.py", encoding="utf-8").read()

vision_prompt = VISION.split("system_prompt = (", 1)[1].split("\n            )", 1)[0]

print("\n[1] Модель зрения обязана отделять увиденное от истолкованного")
check("требование сформулировано",
      "ПРАВИЛА ДОСТОВЕРНОСТИ" in vision_prompt, "правил достоверности нет")
check("наблюдение отделяется от вывода",
      "Отделяй наблюдение от истолкования" in vision_prompt)
check("запрет ставить диагноз по одному снимку",
      "НЕ ставь диагноз по одному снимку" in vision_prompt)
check("пределы снимка признаются вслух",
      "не дают оценить область" in vision_prompt, "нет требования признать плохой ракурс")
check("«не видно» объявлено допустимым ответом",
      "полноценный ответ" in vision_prompt)

print("\n[2] Числа с картинки — только если они читаются")
check("запрет на выдуманные величины",
      "не читаются на снимке" in vision_prompt, "числа ничем не ограничены")
for unit in ("миллиметры", "длина канала", "размер дефекта"):
    check(f"пример «{unit}» назван", unit in vision_prompt)

print("\n[3] Прежняя формулировка, приглашавшая называть патологию, убрана")
check("«Опиши клиническую картину (патология…)» больше нет",
      "Опиши клиническую картину на русском языке (патология" not in vision_prompt,
      "старая формулировка на месте")
check("вместо неё — что видно на самом деле",
      "что НА САМОМ ДЕЛЕ видно" in vision_prompt)

print("\n[4] Отвечающий не принимает описание за факт")
media_prompt = ASSISTANT.split("Описание изображения (распознано моделью", 1)[1][:1200]
check("описание помечено как прочтение машиной",
      "это НЕ факт" in media_prompt, "описание подаётся как факт")
check("оговорка о галлюцинации зрения есть",
      "ДОСТОВЕРНОСТЬ ОПИСАНИЯ" in media_prompt)
check("запрет строить категоричный вывод на одной детали",
      "категоричный вывод" in media_prompt)
check("требуется назвать, что проверить",
      "стоило бы проверить" in media_prompt, "нет требования предложить доп. обследование")
for probe in ("КТ", "анамнез"):
    check(f"«{probe}» назван как способ проверки", probe in media_prompt)

print("\n[5] Ограничения не подменили собой полезность")
check("описание материалов и этапа лечения по-прежнему требуется",
      "материалы" in vision_prompt and "этап лечения" in vision_prompt)
check("разбор текста на картинке сохранён", "разбери его смысл" in vision_prompt)
check("немедицинские картинки по-прежнему обрабатываются",
      "мем, котик" in vision_prompt)
check("ограничение длины сохранено", "3-5 предложений" in vision_prompt)
check("требование русского языка сохранено", "СТРОГО НА РУССКОМ" in vision_prompt)

print("\n[6] Мем-ветка не обвешана медицинскими оговорками")
meme_prompt = ASSISTANT.split("Коллега кинул мем или бытовую картинку.", 1)[1][:900]
check("в шутливой ветке нет клинических предупреждений",
      "ДОСТОВЕРНОСТЬ ОПИСАНИЯ" not in meme_prompt,
      "медицинская оговорка попала в ответ на котика")

print("\n[7] Ответ модели проверяется на язык, а не принимается на веру")
# Инструкции «отвечай строго по-русски» оказалось мало: замер по живой базе —
# 1285 английских описаний из 3375, то есть 38%. Они уходят в промпт русского
# чата, и отвечающая модель вынуждена переводить чужой текст.
import vision

for good in ("Прицельный снимок 36 зуба, очаг разрежения у апекса.",
             "Установлен Straumann BLX, абатмент Variobase, торк 35 Нсм",
             "Коронка e.max на 21, краевое прилегание удовлетворительное. CAD/CAM",
             "КЛКТ 3D"):
    check(f"русское описание принимается: «{good[:38]}»",
          vision._is_mostly_cyrillic(good) is True)

for bad in ("The image depicts a dental radiograph showing a tooth.",
            "Unfortunately, the provided image is not a dental image."):
    check(f"английское отвергается: «{bad[:38]}»",
          vision._is_mostly_cyrillic(bad) is False)

check("абракадабра из чужих письменностей отвергается",
      vision._is_mostly_cyrillic("=`ື່ອ picojax expandingື່ອ associative romatРанее MAL карта") is False,
      "мусор модели прошёл как описание")
check("пустое отвергается", vision._is_mostly_cyrillic("") is False)
check("None не роняет", vision._is_mostly_cyrillic(None) is False)

# Осознанный компромисс: смешанный текст с русскими вкраплениями проходит.
# Ужесточение порога отсекло бы описания вроде «Straumann BLX, абатмент
# Variobase», которых больше и которые ценнее.
check("порог допускает латиницу брендов",
      vision.VISION_MIN_CYRILLIC_RATIO <= 0.4,
      f"порог {vision.VISION_MIN_CYRILLIC_RATIO} отсечёт описания с названиями материалов")

source = io.open("vision.py", encoding="utf-8").read()
check("непрошедший ответ уводит к следующей модели каскада",
      "trying next model" in source, "нет перехода к следующей модели")
check("английский ответ сохраняется как запасной, а не теряется",
      "english_fallback" in source, "нет запасного варианта")
check("использование запасного пишется в лог",
      "no Russian answer from cascade" in source)

print("\n[8] Промпт зрения не раздут")
# Он уходит с каждым изображением, поэтому размер имеет цену.
rendered = re.sub(r'^\s*f?"|"\s*$', "", vision_prompt, flags=re.M)
check(f"длина промпта разумна ({len(rendered)} символов)", len(rendered) < 2500,
      f"got {len(rendered)}")

print(f"\n{'='*62}\nPASSED: {len(PASS)}   FAILED: {len(FAIL)}")
if FAIL:
    print("Провалено: " + ", ".join(FAIL))
sys.exit(1 if FAIL else 0)
