async def _safe_send_chairside(bot_client, event, text: str, buttons=None):
    """Безопасная отправка chairside-ответа с защитой от удаленного сообщения (Ghost Reply)."""
    chat_id = event.chat_id
    msg_id = getattr(getattr(event, "message", None), "id", getattr(event, "id", None))
    try:
        if msg_id:
            return await bot_client.send_message(chat_id, text, buttons=buttons, reply_to=msg_id, parse_mode="html")
        else:
            return await bot_client.send_message(chat_id, text, buttons=buttons, parse_mode="html")
    except Exception as e:
        logger.warning(f"Failed to send chairside with reply_to={msg_id}: {e}. Retrying directly without reply_to.")
        return await bot_client.send_message(chat_id, text, buttons=buttons, parse_mode="html")


