def lookup_file_system(query: str) -> Optional[Dict[str, Any]]:
    """Поиск эндодонтической системы по ключевым словам или коду."""
    q = query.lower().strip()
    aliases = {
        "protaper": "protaper_ultimate",
        "протейпер": "protaper_ultimate",
        "ultimate": "protaper_ultimate",
        "waveone": "waveone_gold",
        "вейван": "waveone_gold",
        "вейвон": "waveone_gold",
        "soco": "soco_sc_pro",
        "соко": "soco_sc_pro",
        "sc pro": "soco_sc_pro",
        "rotate": "vdw_rotate",
        "ротейт": "vdw_rotate",
        "reciproc": "reciproc_blue",
        "реципрок": "reciproc_blue",
        "rogin": "rogin_super",
        "роджин": "rogin_super",
        "рогин": "rogin_super",
        "denco": "denco_super",
        "денко": "denco_super",
        "edgetaper": "edgetaper_platinum",
        "edge": "edgetaper_platinum",
        "xp-endo": "xp_endo_shaper",
        "хп эндо": "xp_endo_shaper",
        "shaper": "xp_endo_shaper",
    }
    for k, v in aliases.items():
        if k in q:
            return ENDO_FILE_CATALOG.get(v)
    for sys_key, data in ENDO_FILE_CATALOG.items():
        if sys_key in q or data["system_name"].lower() in q or data["brand"].lower() in q:
            return data
    return None


def format_file_system_card(data: Dict[str, Any]) -> str:
    """Форматирует компактную карточку для моментального вывода у кресла."""
    lines = [
        f"⚙️ <b>{html.escape(data['system_name'])}</b> ({html.escape(data['brand'])})",
        "━━━━━━━━━━━━━━━━━━━━━",
        f"🔄 <b>Кинематика:</b> {html.escape(data['motion'])}",
        f"⚡ <b>Базовые обороты (RPM):</b> <code>{data['standard_rpm']} об/мин</code>",
        f"🎛 <b>Рекомендуемый торк:</b> <code>{data['standard_torque']} N·cm</code>",
        "",
        "<b>📋 Спецификация инструментов пачки:</b>"
    ]
    for f in data["files"]:
        ang = f" | {f.angles}" if f.angles else ""
        lines.append(
            f"• <b>{html.escape(f.name)}</b> ({f.size_taper}): <code>{f.rpm} RPM / {f.torque} N·cm</code>{ang}\n"
            f"  └ <i>{html.escape(f.notes)}</i>"
        )
    lines.append("")
    lines.append(f"💡 <b>Chairside Совет:</b> {html.escape(data['tip'])}")
    return "\n".join(lines)


