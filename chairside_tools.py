                f"💊 <b>Назначение антибиотика (при аллергии на пенициллин):</b>\n"
                f"• Препарат: <b>Азитромицин (Сумамед) суспензия 200 мг / 5 мл</b>\n"
                f"• Дозировка: <b>{round(daily_dose * 5 / 200, 1)} мл</b> 1 раз в день\n"
                f"• Курс: строго <b>3 дня подряд</b> в одно и то же время.\n"
                f"• Принимать: строго за 1 час до еды или через 2 часа после еды.\n"
