async def handle_if_chairside_command(bot_client, event, cmd: str) -> bool:
    """
    Проверяет и мгновенно исполняет chairside-команды прямого действия:
    /chairside, /torque, /anes, /fdi, /aae, /sos, /pharma, /preserve.
    """
    if not cmd:
        return False
    clean = cmd.strip()
    if not clean.startswith("/"):
        return False
    parts = clean.split(maxsplit=1)
    first_word = parts[0].lower()
    arg = parts[1].strip() if len(parts) > 1 else ""
    cmd_name = first_word.split("@")[0]

    if cmd_name == "/chairside":
        await handle_chairside_command(bot_client, event, arg)
        return True
    elif cmd_name in ("/torque", "/торк"):
        await handle_torque_command(bot_client, event, arg)
        return True
    elif cmd_name in ("/anes", "/анестезия"):
        await handle_anes_command(bot_client, event, arg)
        return True
    elif cmd_name in ("/fdi", "/зуб"):
        await handle_fdi_command(bot_client, event, arg)
        return True
    elif cmd_name == "/aae":
        await handle_aae_command(bot_client, event, arg)
        return True
    elif cmd_name in ("/sos", "/обломок"):
        clean_lower = arg.strip().lower()
        fast_sos_keywords = ("file", "обломок", "сепарац", "поломк", "hypo", "гипохлорит", "авари", "anes", "анестези", "пульпит", "боль")
        if clean_lower and not any(k in clean_lower for k in fast_sos_keywords):
            return False
        await handle_sos_command(bot_client, event, arg)
        return True
    elif cmd_name in ("/pharma", "/антибиотики", "/нпвп"):
        await handle_pharma_command(bot_client, event, arg)
        return True
    elif cmd_name in ("/preserve", "/феррул", "/сохранение"):
        await handle_preserve_command(bot_client, event, arg)
        return True
    return False

