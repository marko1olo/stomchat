@dataclass
class ToothPrognosisScore:
    total_score: int  # 0 to 100
    verdict: str
    color: str
    reasons: List[str]
    patient_explanation: str


def evaluate_tooth_preservation(
    ferrule_mm: float,
    wall_thickness_mm: float,
    root_fracture_suspected: bool,
    bone_support_percent: int,
    endo_perio_combined: bool,
    furcation_involved: bool
) -> ToothPrognosisScore:
    """Оценка целесообразности сохранения зуба по биомеханическим критериям."""
    score = 100
    reasons = []

    # 1. Феррул (Ferrule)
    if ferrule_mm < 0.5:
        score -= 35
        reasons.append("❌ Отсутствует феррул (<1 мм): нет ободка для кругового обхвата коронкой, риск перелома корня под нагрузкой >80%.")
    elif ferrule_mm < 1.5:
        score -= 15
        reasons.append("⚠️ Дефицит феррула (1.0-1.5 мм): требуется хирургическое удлинение коронковой части или ортодонтическая экструзия.")
    else:
        reasons.append("✅ Достаточный феррул-эффект (>1.5-2 мм).")

    # 2. Толщина стенок
    if wall_thickness_mm < 1.0:
        score -= 15
        reasons.append("⚠️ Истонченные стенки (<1 мм): высокий риск раскола корня штифтовой конструкцией.")

    # 3. Вертикальная трещина корня (Vertical Root Fracture)
    if root_fracture_suspected:
        score = 0
        reasons.append("🛑 АБСОЛЮТНОЕ ПОКАЗАНИЕ К УДАЛЕНИЮ: Вертикальный перелом/трещина корня не подлежит восстановлению. Любые попытки лечения — ятрогения и потеря кости под будущий имплантат.")
        return ToothPrognosisScore(0, "БЕЗУСЛОВНОЕ УДАЛЕНИЕ", "🔴", reasons,
                                   "«В корне зуба образовалась глубокая продольная трещина. Спасти зуб невозможно, корень расколот. Чтобы не потерять окружающую челюстную кость, показано бережное удаление с последующей установкой имплантата».")

    # 4. Костная поддержка
    if bone_support_percent < 30:
        score -= 35
        reasons.append("❌ Критическая потеря кости (<30% длины корня): соотношение коронка/корень неблагоприятное (>1.5:1).")
    elif bone_support_percent < 50:
        score -= 15
        reasons.append("⚠️ Умеренная потеря кости (30-50% длины корня).")

    # 5. Фуркация и пародонт
    if furcation_involved:
        score -= 20
        reasons.append("⚠️ Вовлечение фуркации корней (бифуркационный дефект II-III класса): сложный пародонтологический прогноз.")
    if endo_perio_combined:
        score -= 15
        reasons.append("⚠️ Сочетанное эндо-пародонтальное поражение.")

    score = max(0, min(100, score))

    if score >= 75:
        verdict = "СПАСАТЬ (БЛАГОПРИЯТНЫЙ ПРОГНОЗ)"
        color = "🟢"
        pt_exp = "«Зуб имеет достаточный запас прочности, здоровые стенки выше десны и плотную костную поддержку. Качественное перелечивание каналов и покрытие коронкой позволят зубу служить долгие годы»."
    elif score >= 50:
        verdict = "СОМНИТЕЛЬНЫЙ ПРОГНОЗ (ТРЕБУЕТСЯ ПОДГОТОВКА)"
        color = "🟡"
        pt_exp = "«Зуб можно попытаться сохранить, но ситуация на грани: мало здоровых тканей над десной. Потребуется удлинение коронки зуба десневой пластикой и укрепление перед установкой коронки. Без гарантий при перегрузке»."
    else:
        verdict = "НЕБЛАГОПРИЯТНЫЙ ПРОГНОЗ (РЕКОМЕНДОВАНО УДАЛЕНИЕ)"
        color = "🔴"
        pt_exp = "«Собственных тканей зуба осталось критически мало, костная опора разрушена. Вкладывать деньги в сложное лечение экономически и биологически нецелесообразно: зуб быстро сломается. Разумнее инвестировать в надежный имплантат»."

    return ToothPrognosisScore(score, verdict, color, reasons, pt_exp)


